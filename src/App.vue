<script setup lang="ts">
import { ref, computed } from 'vue';
import Header from './components/Header.vue';
import Hero from './components/Hero.vue';
import WorldModelStages from './components/WorldModelStages.vue';
import ScoreBars from './components/ScoreBars.vue';
import LeaderboardTable from './components/LeaderboardTable.vue';
import TaskExamplesGrid from './components/TaskExamplesGrid.vue';
import MethodologySection from './components/MethodologySection.vue';
import InvertedWhitepaperSection from './components/InvertedWhitepaperSection.vue';
import Footer from './components/Footer.vue';
import {
  BENCHMARK_MODELS,
  DATA_VERSIONS,
  HAS_RESULTS,
  LEADERBOARD_META,
} from './data/benchmarkData';

const activeVersion = ref<string>(DATA_VERSIONS[0] ?? 'v1.1');

const props = withDefaults(
  defineProps<{
    /** Test-only: render the reading notes already expanded for SSR checks. */
    initialReadingNotesOpen?: boolean;
  }>(),
  { initialReadingNotesOpen: false },
);

const showReadingNotes = ref(props.initialReadingNotesOpen);

const versionModels = computed(() =>
  BENCHMARK_MODELS.filter((model) => model.version === activeVersion.value),
);

const scrollToSection = (sectionId: string) => {
  const el = document.getElementById(sectionId);
  if (el) {
    el.scrollIntoView({ behavior: 'smooth' });
  }
};
</script>

<template>
  <div class="min-h-screen flex flex-col bg-background text-foreground transition-colors">
    <Header @navigate="scrollToSection" />

    <main class="flex-1">
      <Hero @navigate="scrollToSection" />

      <WorldModelStages @navigate="scrollToSection" />

      <div class="max-w-5xl mx-auto px-4 sm:px-6">
        <!-- Leaderboard -->
        <section id="leaderboard" class="mt-14 sm:mt-16 scroll-mt-20">
          <div class="mb-5 flex flex-wrap items-baseline justify-between gap-x-4 gap-y-1">
            <h2 class="text-xl sm:text-2xl font-medium tracking-tight text-foreground">
              Leaderboard
            </h2>
            <span class="text-[12px] font-mono text-muted-foreground">
              {{ LEADERBOARD_META.benchmark }} · data generated by starlife_eval
            </span>
          </div>
          <p data-scope-note class="mb-2 text-[12px] leading-relaxed text-muted-foreground">
            Scope: world-model grounding / world-state understanding — single-step two-frame state
            update. Multi-step rollout, action-conditioned dynamics and planning are not scored in v1.
          </p>
          <p data-track-summary class="mb-2 text-[12px] leading-relaxed text-muted-foreground">
            We evaluate two submission tracks: supervised local heads
            (<span class="font-mono text-foreground">local-heads</span>) and zero-shot general
            models (<span class="font-mono text-foreground">zero-shot</span>). Rankings use the same
            7-dimension composite for both; per-dimension scores and 95% bootstrap intervals are
            shown so each claim can be checked. See <strong class="font-medium text-foreground">How to read</strong>
            for track differences and rank stability.
          </p>

          <div class="mb-5">
            <button
              type="button"
              data-reading-notes-toggle
              :aria-expanded="showReadingNotes"
              aria-controls="reading-notes"
              class="inline-flex items-center gap-1.5 text-[12px] leading-none text-muted-foreground hover:text-foreground transition-colors cursor-pointer"
              @click="showReadingNotes = !showReadingNotes"
            >
              <span class="reading-arrow" :data-open="showReadingNotes" aria-hidden="true" />
              <span>{{ showReadingNotes ? 'Hide reading notes' : 'How to read' }}</span>
            </button>

            <div
              v-if="showReadingNotes"
              id="reading-notes"
              data-reading-notes
              class="mt-2 max-w-3xl text-[12px] leading-relaxed text-muted-foreground"
            >
              <ul class="list-disc space-y-1.5 pl-4">
                <li>
                  Scope: this leaderboard measures world-model grounding (world-state understanding)
                  — whether a model can turn a scene change into a correct structured world-state
                  update. It does not score multi-step rollout, action-conditioned dynamics or
                  planning.
                </li>
                <li>
                  Track difference: local heads were trained on the in-domain split; zero-shot models
                  have never seen it. Both tracks are listed side by side — the composite does not mix
                  scores across tracks, and the track tag (L / Z) stays visible on every row.
                </li>
                <li>
                  Composite: equal-weight average of the 7 dimensions (0-100). Use the dimension tabs
                  above the bars to re-rank by any single dimension; each bar carries a 95% bootstrap
                  interval over the 60 pairs.
                </li>
                <li>
                  Rank stability: under random weightings the local row stays first in 88% of draws,
                  while the cloud ordering can shift by about ±1 slot; weighting only change detection
                  puts cloud models ahead. Full sweep:
                  <span class="font-medium text-foreground">reliability report</span>.
                </li>
              </ul>
            </div>
          </div>

          <template v-if="HAS_RESULTS">
            <ScoreBars :models="versionModels" />

            <LeaderboardTable
              :all-models="BENCHMARK_MODELS"
              :active-version="activeVersion"
              :versions="DATA_VERSIONS"
              :meta="LEADERBOARD_META"
              @update:active-version="activeVersion = $event"
            />
          </template>

          <!-- Empty state: the page stays usable when the generated JSON is missing or empty -->
          <div v-else class="border border-border bg-card p-8 sm:p-10 text-center">
            <h3 class="text-base font-medium text-foreground">No evaluation results yet</h3>
            <p class="mt-2 text-sm text-muted-foreground leading-relaxed">
              <span class="font-mono text-foreground">src/data/leaderboard.generated.json</span>
              has not been generated or is empty. The backend generates the real leaderboard after
              an evaluation run; refresh this page once it exists.
            </p>
            <code class="mt-4 inline-block max-w-full overflow-x-auto border border-border bg-muted/30 px-3 py-2 text-[11px] font-mono text-foreground">
              python -m starlife_eval leaderboard --run runs/v2g_real --out
              third_party/openwsv/src/data/leaderboard.generated.json
            </code>
          </div>
        </section>

        <TaskExamplesGrid />
        <MethodologySection />
      </div>

      <InvertedWhitepaperSection />
    </main>

    <Footer />
  </div>
</template>

