<script setup lang="ts">
import { ref, computed, watch } from 'vue';
import Header from './components/Header.vue';
import Hero from './components/Hero.vue';
import ScatterPlot from './components/ScatterPlot.vue';
import LeaderboardTable from './components/LeaderboardTable.vue';
import TaskExamplesGrid from './components/TaskExamplesGrid.vue';
import MethodologySection from './components/MethodologySection.vue';
import InvertedWhitepaperSection from './components/InvertedWhitepaperSection.vue';
import Footer from './components/Footer.vue';
import {
  BENCHMARK_MODELS,
  DATA_VERSIONS,
  HAS_RESULTS,
  LEADERBOARD_META,
  firstAvailableMetric,
  hasMetricData,
  type MetricKey,
} from './data/benchmarkData';

const activeVersion = ref<string>(DATA_VERSIONS[0] ?? 'v1.1');

const versionModels = computed(() =>
  BENCHMARK_MODELS.filter((model) => model.version === activeVersion.value),
);

const activeMetric = ref<MetricKey | null>(firstAvailableMetric(versionModels.value));

/** 切换版本后，若当前 X 维度在新版本里没有实测值，自动回退。 */
watch(versionModels, (models) => {
  if (activeMetric.value && hasMetricData(models, activeMetric.value)) return;
  activeMetric.value = firstAvailableMetric(models);
});

const scrollToSection = (sectionId: string) => {
  const el = document.getElementById(sectionId);
  if (el) {
    el.scrollIntoView({ behavior: 'smooth' });
  }
};
</script>

<template>
  <div class="min-h-screen flex flex-col bg-background text-foreground transition-colors">
    <Header @navigate="scrollToSection" />

    <main class="flex-1">
      <Hero @navigate="scrollToSection" />

      <div class="max-w-5xl mx-auto px-4 sm:px-6">
        <!-- Leaderboard -->
        <section id="leaderboard" class="mt-14 sm:mt-16 scroll-mt-20">
          <div class="mb-5 flex flex-wrap items-baseline justify-between gap-x-4 gap-y-1">
            <h2 class="text-xl sm:text-2xl font-medium tracking-tight text-foreground">
              Leaderboard
            </h2>
            <span class="text-[12px] font-mono text-muted-foreground">
              {{ LEADERBOARD_META.benchmark }} · data generated by starlife_eval
            </span>
          </div>

          <template v-if="HAS_RESULTS">
            <ScatterPlot
              :models="versionModels"
              :all-models-count="versionModels.length"
              :active-metric="activeMetric"
              :active-version="activeVersion"
              :versions="DATA_VERSIONS"
              :meta="LEADERBOARD_META"
              @update:active-metric="activeMetric = $event"
              @update:active-version="activeVersion = $event"
            />

            <LeaderboardTable
              :all-models="BENCHMARK_MODELS"
              :active-version="activeVersion"
              :versions="DATA_VERSIONS"
              :meta="LEADERBOARD_META"
              @update:active-version="activeVersion = $event"
            />
          </template>

          <!-- 空态：generated json 缺失/为空时页面照常可用 -->
          <div v-else class="border border-border bg-card p-8 sm:p-10 text-center">
            <h3 class="text-base font-medium text-foreground">尚无评测结果</h3>
            <p class="mt-2 text-sm text-muted-foreground leading-relaxed">
              <span class="font-mono text-foreground">src/data/leaderboard.generated.json</span>
              尚未生成或为空。评测完成后由后端生成真实榜单，刷新本页即可显示。
            </p>
            <code class="mt-4 inline-block max-w-full overflow-x-auto border border-border bg-muted/30 px-3 py-2 text-[11px] font-mono text-foreground">
              python -m starlife_eval leaderboard --run runs/v2g_real --out
              third_party/openwsv/src/data/leaderboard.generated.json
            </code>
          </div>
        </section>

        <TaskExamplesGrid />
        <MethodologySection />
      </div>

      <InvertedWhitepaperSection />
    </main>

    <Footer />
  </div>
</template>
